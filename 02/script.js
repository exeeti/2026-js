function createTable(a, b) {
  let str = "<table>";
  for (let i = 0; i < a; i++) {
    str = str + "<tr>";
    for (let j = 0; j < b; j++) {
      str = str + `<td data-i=${i} data-j=${j}></td>`;
    }
    str = str + "</tr>";
  }
  str = str + "</table>";
  return str;
}

