let tables = clock.querySelectorAll("table");

function drawDigit(table, coordinates) {
  for (let i = 0; i < coordinates.length; i++) {
    let row = coordinates[i][0];
    let column = coordinates[i][1];

    let cell = table.querySelector(
      `td[data-i="${row}"][data-j="${column}"]`
    );

    if (cell) {
      cell.className = "marked";
    }
  }
}

const region = document.querySelector('#region');

function updateClock() {
  let now = new Date();

  let time = now.toLocaleTimeString('ru-RU', {
    timeZone: region.value,
    hour: '2-digit',
    minute: '2-digit',
    hourCycle: 'h23'
  });

  let numbers = time.replace(':', '');

  for (let i = 0; i < 4; i++) {
    tables[i].querySelectorAll('td').forEach(cell => {
      cell.className = '';
    });

    drawDigit(tables[i], JSON.parse(digits[numbers[i]]));
  }
}

region.addEventListener('change', updateClock);
updateClock();
setInterval(updateClock, 1000);

